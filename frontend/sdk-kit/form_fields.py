"""List every field an extension can address on a bespoke form (a DeskField with a `name`).

    python frontend/sdk-kit/form_fields.py > docs/extension-sdk-form-fields.md

Reads the views that call useExtensionFields("<DocType>") (plus the components listed in COMPONENTS that
draw their fields). tests/test_field_names.py fails when the committed docs/extension-sdk-form-fields.md is out of
date, so the reference never drifts from the forms.
"""

import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src"
# Components that draw a form's fields for a view that adopted useExtensionFields (an edit modal, or the
# fields block a screen shares between its create and edit forms): they belong to that view's DocType.
COMPONENTS = {
	"views/project-detail/ProjectEditModal.vue": "Project",
	"components/CrewFormFields.vue": "Crew",
	"components/AttendanceFormFields.vue": "Field Attendance",
	"components/FieldEmployeeFormFields.vue": "Employee",
}

FIELD = re.compile(r"<DeskField\b(.*?)>(.*?)</DeskField>", re.S)
NAMED = re.compile(r'(?<![:\w-])name="([a-z0-9_]+)"')
ADOPT = re.compile(r'useExtensionFields\(\s*"([^"]+)"')


def label_of(attrs: str) -> str:
	m = re.search(r"""(?<![:\w-])label="([^"]*)"|:label="[^"]*?__\(\s*['"]([^'"]+)['"]""", attrs)
	return (m.group(1) or m.group(2)) if m else ""


def scan():
	"""{doctype: [(name, label, required, screen)]} and the count of fields still unnamed per file."""
	forms: dict[str, list] = {}
	unnamed: dict[str, int] = {}
	files = {p.relative_to(SRC).as_posix(): p for p in SRC.rglob("*.vue")}
	for rel, path in sorted(files.items()):
		text = path.read_text()
		doctype = COMPONENTS.get(rel) or (ADOPT.search(text).group(1) if ADOPT.search(text) else None)
		if not doctype:
			continue
		for attrs, _body in FIELD.findall(text):
			named = NAMED.search(attrs)
			if not named:
				unnamed[rel] = unnamed.get(rel, 0) + 1
				continue
			required = bool(re.search(r"(?<![:\w-])required(?![\w-])", attrs))
			forms.setdefault(doctype, []).append((named.group(1), label_of(attrs), required, Path(rel).stem))
	return forms, unnamed


def render() -> str:
	forms, _ = scan()
	out = [
		"# Extension SDK: form fields you can address",
		"",
		"Generated by `frontend/sdk-kit/form_fields.py` from the forms themselves. Each row is a field of a",
		"bespoke form. Use its **name** in `sdk.doctype(<DocType>).on({ fieldRules: { <name>: {...} } })`,",
		"and in the slots `form.<DocType>.before.field.<name>` / `form.<DocType>.after.field.<name>`.",
		"A field Core marks required cannot be hidden by an extension.",
		"",
		"The name is the form's own name for the field, usually the DocType fieldname. A few forms keep a",
		"camelCase key in their model (`templateCode`); the name here is its snake_case form",
		"(`template_code`), which is what a rule's `ctx.form` lookup and `required` check use.",
		"",
	]
	for doctype in sorted(forms):
		out += [
			f"## {doctype}",
			"",
			"| Name | Label | Core requires it | Screen |",
			"| --- | --- | --- | --- |",
		]
		seen = set()
		for name, label, required, screen in forms[doctype]:
			if (name, screen) in seen:
				continue
			seen.add((name, screen))
			out.append(f"| `{name}` | {label or '—'} | {'yes' if required else ''} | {screen} |")
		out.append("")
	return "\n".join(out)


if __name__ == "__main__":
	sys.stdout.write(render())
